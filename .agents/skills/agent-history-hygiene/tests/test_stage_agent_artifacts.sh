if [ "$empty_hooks_rc" = "6" ] && ! contains "$empty_hooks_output" '/prepare-commit-msg' && \
   [ ! -e "$repo_empty_hooks/.pre-commit-config.yaml" ]; then
  pass "configured-empty core.hooksPath fails before constructing a root hook path"
